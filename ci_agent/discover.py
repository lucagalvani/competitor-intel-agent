"""`ci-agent init`: research any company's competitors and write a ready-to-use config.yaml."""

from __future__ import annotations

from datetime import date

import yaml

from .llm import LLM

DISCOVERY_SCHEMA = {
    "type": "object",
    "properties": {
        "company": {
            "type": "object",
            "properties": {
                "name": {"type": "string"},
                "website": {"type": "string"},
                "description": {"type": "string"},
            },
            "required": ["name", "website", "description"],
            "additionalProperties": False,
        },
        "competitors": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "name": {"type": "string"},
                    "website": {"type": "string"},
                    "why": {"type": "string"},
                    "pages": {
                        "type": "array",
                        "items": {
                            "type": "object",
                            "properties": {
                                "type": {"type": "string", "enum": ["homepage", "pricing", "changelog", "careers", "blog"]},
                                "url": {"type": "string"},
                            },
                            "required": ["type", "url"],
                            "additionalProperties": False,
                        },
                    },
                },
                "required": ["name", "website", "why", "pages"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["company", "competitors"],
    "additionalProperties": False,
}


def discover(llm: LLM, company: str, max_competitors: int = 6, market: str = "") -> dict:
    """Two steps: free web research first, then turn the findings into structured JSON."""
    focus = f" Focus on the {market} market." if market else ""
    research = llm.research(
        "You are a meticulous competitive intelligence researcher.",
        f"""Today is {date.today().isoformat()}. Research the company "{company}".{focus}
1. Find its official website and describe in two sentences what it sells and to whom.
2. Identify its {max_competitors} most relevant direct competitors (same buyers, same problem).
   Prefer competitors that buyers actually compare it with.
3. For each competitor find the exact URLs of: homepage, pricing page, changelog / release notes,
   careers page, blog. Only list URLs you have verified exist; skip ones you can't find.
Report your findings as a plain list.""",
    )
    return llm.json(
        "You convert research notes into structured data. Use only facts present in the notes.",
        f"Convert these research notes into the requested structure:\n\n{research}",
        DISCOVERY_SCHEMA,
    )


def build_config(found: dict) -> dict:
    competitors = []
    for comp in found["competitors"]:
        seen = set()
        sources = []
        for page in comp["pages"]:
            if page["type"] in seen or not page["url"].startswith("http"):
                continue
            seen.add(page["type"])
            sources.append({"type": page["type"], "url": page["url"]})
        if "homepage" not in seen and comp["website"].startswith("http"):
            sources.insert(0, {"type": "homepage", "url": comp["website"]})
        sources += [{"type": "news"}, {"type": "reviews"}]
        competitors.append({"name": comp["name"], "website": comp["website"], "sources": sources})
    return {
        "company": found["company"],
        "competitors": competitors,
        "llm": {"model": "claude-opus-5-5", "effort": "medium", "fallbacks": True},
        "frameworks": ["battlecard", "positioning", "swot"],
        "data_dir": "data",
        "outputs": ["github_issue"],
        "alerts": {"min_significance": "high", "outputs": ["github_issue"]},
        "github": {"repo": "", "labels": ["competitive-intel"]},
        "email": {"to": []},
        "notify_when_no_changes": False,
        "language": "English",
    }


def to_yaml(config: dict, found: dict) -> str:
    header = "# Generated by `ci-agent init`. Review the competitors and URLs before the first run.\n"
    for comp in found["competitors"]:
        header += f"# - {comp['name']}: {comp['why']}\n"
    return header + "\n" + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=120)
